/* WordPress-style admin shell: top admin bar + menu details. Visual/navigation only —
   no data writes. Works with the menu generated by scripts/sync-admin-navigation.py. */
(function () {
  'use strict';
  var doc = document;
  function byId(id) { return doc.getElementById(id); }
  function esc(s) { return String(s == null ? '' : s).replace(/[&<>"]/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]; }); }

  function sessionName() {
    try {
      var s = window.MaAdmin && window.MaAdmin.getSession && window.MaAdmin.getSession();
      return (s && (s.name || s.email)) || '';
    } catch (e) { return ''; }
  }

  function buildAdminBar() {
    if (byId('wpAdminBar')) return;
    var bar = doc.createElement('div');
    bar.id = 'wpAdminBar';
    bar.className = 'wp-adminbar';
    bar.setAttribute('role', 'navigation');
    bar.setAttribute('aria-label', 'Toolbar');
    var name = sessionName();
    bar.innerHTML =
      '<ul class="wp-adminbar-left">' +
        '<li class="wp-ab-menu"><button type="button" id="wpAbMenu" aria-label="Menu"><svg viewBox="0 0 24 24" width="20" height="20" aria-hidden="true"><path fill="currentColor" d="M3 6h18v2H3zm0 5h18v2H3zm0 5h18v2H3z"/></svg></button></li>' +
        '<li class="wp-ab-site"><a href="index.html" target="_blank" rel="noopener" title="Visit store"><svg viewBox="0 0 24 24" width="18" height="18" aria-hidden="true"><path fill="currentColor" d="M12 3 2 11h3v9h6v-6h2v6h6v-9h3z"/></svg><span>Muslim Abaya</span></a></li>' +
        '<li class="wp-ab-new"><a href="admin-order-new.html" aria-haspopup="true"><svg viewBox="0 0 24 24" width="16" height="16" aria-hidden="true"><path fill="currentColor" d="M11 4h2v7h7v2h-7v7h-2v-7H4v-2h7z"/></svg><span>New</span></a>' +
          '<ul class="wp-ab-sub"><li><a href="admin-order-new.html">Order</a></li><li><a href="product-manager.html?action=new">Product</a></li></ul></li>' +
        '<li class="wp-ab-link"><a href="admin-orders.html">Orders</a></li>' +
        '<li class="wp-ab-purge"><button type="button" aria-haspopup="true" aria-label="Purge cache" title="Purge cache"><svg class="wp-ab-purge-icon" viewBox="0 0 24 24" width="20" height="20" aria-hidden="true"><path fill="currentColor" d="M12 1.5 22.5 12 12 22.5 1.5 12zm0 4.2L5.7 12l6.3 6.3 6.3-6.3z"/><path fill="currentColor" d="M12 8.6 15.4 12 12 15.4 8.6 12z"/></svg></button>' +
          '<ul class="wp-ab-sub wp-ab-purge-sub">' +
            '<li><button type="button" id="wpAbPurgePage">Purge this page</button></li>' +
            '<li><button type="button" id="wpAbPurgeAll">Purge All</button></li>' +
            '<li><button type="button" id="wpAbPurgeLocal">Purge All - Browser Cache</button></li>' +
          '</ul></li>' +
      '</ul>' +
      '<ul class="wp-adminbar-right">' +
        '<li class="wp-ab-user"><span>Howdy' + (name ? ', ' + esc(name) : '') + '</span><span class="wp-ab-avatar" aria-hidden="true"></span>' +
          '<ul class="wp-ab-sub wp-ab-sub-right"><li><button type="button" id="wpAbLogout">Log Out</button></li></ul></li>' +
      '</ul>';
    doc.body.insertBefore(bar, doc.body.firstChild);
    byId('wpAbMenu').addEventListener('click', function () {
      var btn = byId('admMenuBtn') || byId('pnMenuBtn') || byId('menuBtn');
      if (btn) btn.click();
    });
    byId('wpAbPurgePage').addEventListener('click', purgePage);
    byId('wpAbPurgeAll').addEventListener('click', purgeAll);
    byId('wpAbPurgeLocal').addEventListener('click', purgeBrowser);
    byId('wpAbLogout').addEventListener('click', function () {
      var out = byId('admLogout');
      if (out) { out.click(); return; }
      try { if (window.MaAdmin && window.MaAdmin.logout) window.MaAdmin.logout(); } catch (e) {}
      location.href = 'admin-login.html';
    });
  }

  /* ---------- Purge (like LiteSpeed Cache's admin-bar menu) ---------- */
  function notice(text, kind) {
    var box = byId('wpAbNotice');
    if (!box) { box = doc.createElement('div'); box.id = 'wpAbNotice'; box.setAttribute('role', 'status'); doc.body.appendChild(box); }
    box.className = 'wp-ab-notice' + (kind ? ' is-' + kind : '');
    box.textContent = text;
    clearTimeout(notice.t);
    notice.t = setTimeout(function () { box.className = 'wp-ab-notice is-hidden'; }, kind === 'busy' ? 60000 : 9000);
  }
  var purging = false;
  // Whole site: a fresh build + deployment from the newest products and settings (2–4 minutes).
  function closeMenus() { try { if (doc.activeElement && doc.activeElement.blur) doc.activeElement.blur(); } catch (e) {} }
  function purgeAll() {
    closeMenus();
    if (purging) return;
    var s = null;
    try { s = window.MaAdmin && window.MaAdmin.getSession && window.MaAdmin.getSession(); } catch (e) {}
    if (!s || !s.token) { notice('আবার লগইন করুন, তারপর Purge All চাপুন।', 'error'); return; }
    purging = true;
    notice('Purge All শুরু হচ্ছে…', 'busy');
    fetch('/api/admin-purge', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ Token: s.token }) })
      .then(function (r) { return r.json().catch(function () { return { ok: false, error: 'HTTP_' + r.status }; }); })
      .then(function (res) {
        if (res.ok) notice('Purge All শুরু হয়েছে। পুরো সাইট নতুন করে তৈরি হচ্ছে — ২–৪ মিনিট পর সব পেজে সর্বশেষ সংস্করণ দেখাবে।', 'ok');
        else if (res.error === 'TOO_SOON') notice('একটু আগেই Purge All চালানো হয়েছে। ' + Math.ceil((res.retryAfter || 60) / 60) + ' মিনিট পর আবার চেষ্টা করুন।', 'error');
        else if (res.error === 'NOT_LOGGED_IN' || res.error === 'OWNER_ONLY') notice('শুধু মালিকের অ্যাকাউন্ট Purge All চালাতে পারে। আবার লগইন করে দেখুন।', 'error');
        else if (res.error === 'AUTH_UNAVAILABLE') notice('অ্যাডমিন পরিচয় যাচাই করা যাচ্ছে না। কিছুক্ষণ পর আবার চেষ্টা করুন; সমস্যা থাকলে Google সংযোগ যাচাই করুন।', 'error');
        else if (res.error === 'NOT_CONFIGURED') notice('Purge All-এর সার্ভার সেটআপ সম্পূর্ণ নয়। Cloudflare-এর GitHub সংযোগ ও প্রয়োজনীয় সেটিংস যাচাই করুন।', 'error');
        else if (res.error === 'COMMIT_ERROR' || res.error === 'GITHUB_ERROR') notice('সাইট আপডেট শুরু করা যায়নি। GitHub সংযোগ পরীক্ষা করে আবার চেষ্টা করুন।', 'error');
        else notice('Purge All চালু করা যায়নি। কিছুক্ষণ পর আবার চেষ্টা করুন।', 'error');
      })
      .catch(function () { notice('ইন্টারনেট সংযোগ পাওয়া যায়নি। আবার চেষ্টা করুন।', 'error'); })
      .then(function () { purging = false; });
  }
  // This page only: fetch it again past the browser cache and reload with fresh data.
  function purgePage() {
    closeMenus();
    notice('এই পেজ নতুন করে লোড হচ্ছে…', 'busy');
    var done = function () { location.reload(); };
    try { fetch(location.href, { cache: 'reload', credentials: 'same-origin' }).then(done, done); } catch (e) { done(); }
  }
  // This browser only: saved copies the admin/site keep locally. Login, unsaved work and preferences stay.
  var LOCAL_CACHE_KEYS = ['ma_public_stock_status_v1', 'ma_api_health_v1', 'ma_admin_edge_off'];
  function purgeBrowser() {
    closeMenus();
    notice('এই ব্রাউজারের cache মোছা হচ্ছে…', 'busy');
    LOCAL_CACHE_KEYS.forEach(function (k) { try { localStorage.removeItem(k); } catch (e) {} try { sessionStorage.removeItem(k); } catch (e2) {} });
    var jobs = [];
    try { if (window.caches && caches.keys) jobs.push(caches.keys().then(function (keys) { return Promise.all(keys.map(function (k) { return caches.delete(k); })); })); } catch (e3) {}
    try {
      if (navigator.serviceWorker && navigator.serviceWorker.getRegistrations) {
        jobs.push(navigator.serviceWorker.getRegistrations().then(function (regs) { return Promise.all(regs.map(function (r) { return r.update().catch(function () {}); })); }));
      }
    } catch (e4) {}
    Promise.all(jobs).catch(function () {}).then(function () { location.reload(); });
  }

  function tuneSidebar() {
    var sidebar = byId('pnSide') || byId('admSidebar') || doc.querySelector('.adm-sidebar');
    if (!sidebar) return;
    // Products › Add new product is the same file with ?action=new.
    var here = (location.pathname.split('/').pop() || '') + location.search;
    if (/product-manager\.html\?action=new/.test(here)) {
      sidebar.querySelectorAll('.adm-nav-child').forEach(function (a) {
        var on = /action=new/.test(a.getAttribute('href') || '');
        a.classList.toggle('is-current', on);
        if (on) a.setAttribute('aria-current', 'page'); else a.removeAttribute('aria-current');
      });
    }
    // WordPress keeps "Collapse menu" at the bottom of the sidebar.
    var collapse = byId('admCollapse'), foot = sidebar.querySelector('.adm-sidebar-foot');
    if (collapse && foot && collapse.parentNode !== foot) {
      collapse.classList.add('wp-collapse');
      if (!collapse.querySelector('.wp-collapse-label')) collapse.insertAdjacentHTML('beforeend', '<span class="wp-collapse-label">Collapse menu</span>');
      foot.appendChild(collapse);
    }
    // Keep Cache Manager reachable from the Settings group on every admin page.
    var settingsGroup = Array.prototype.find.call(sidebar.querySelectorAll('.adm-nav-group'), function (group) {
      var top = group.querySelector('.adm-nav-top');
      return top && /settings|সেটিংস/i.test(top.textContent || '');
    });
    if (settingsGroup) {
      var children = settingsGroup.querySelector('.adm-nav-children');
      if (children && !children.querySelector('a[href="admin-cache-manager.html"]')) {
        var cacheLink = doc.createElement('a');
        cacheLink.className = 'adm-sidebar-item adm-nav-child';
        cacheLink.href = 'admin-cache-manager.html';
        cacheLink.textContent = 'Cache Manager';
        if ((location.pathname.split('/').pop() || '') === 'admin-cache-manager.html') {
          cacheLink.classList.add('is-current');
          cacheLink.setAttribute('aria-current', 'page');
        }
        children.appendChild(cacheLink);
      }
    }
    // Keyboard: the flyout opens on focus (CSS :focus-within); Escape closes it.
    sidebar.addEventListener('keydown', function (e) {
      if (e.key !== 'Escape') return;
      var group = e.target.closest && e.target.closest('.adm-nav-group');
      var top = group && group.querySelector('.adm-nav-top');
      if (top && doc.activeElement !== top) top.focus();
    });
  }

  /* ---------- Smart toggles: on/off settings show as switches ----------
     Only settings that turn something on or off become switches; checkboxes that pick rows, categories
     or brands stay checkboxes. The <input type="checkbox"> itself is restyled (role="switch"), so every
     page's own code keeps reading .checked and hearing "change" exactly as before. */
  var SWITCH_SELECTOR = [
    'input[type=checkbox][data-switch]',
    '#fUnread', '#showEmptyToggle', '#szOvUseTemplate',
    'input[data-cat-enabled]', '.sz-check input[data-f="enabled"]', '.sz-check input[data-f="required"]', '.sz-check input[data-f="allowCustom"]',
    'input[data-ef="virtual"]', 'input[data-ef="downloadable"]', 'input[data-ef="manageStock"]',
    'input[data-ef="soldIndividually"]', 'input[data-ef="reviewsAllowed"]', 'input[data-ef="featured"]'
  ].join(',');
  function upgradeSwitches(root) {
    var list = [];
    try {
      if (root.matches && root.matches(SWITCH_SELECTOR)) list.push(root);
      if (root.querySelectorAll) list = list.concat(Array.prototype.slice.call(root.querySelectorAll(SWITCH_SELECTOR)));
    } catch (e) { return; }
    list.forEach(function (el) {
      if (el.type !== 'checkbox' || el.classList.contains('ma-switch-pill')) return;
      el.classList.add('ma-switch-pill');
      el.setAttribute('role', 'switch');
      el.setAttribute('aria-checked', el.checked ? 'true' : 'false');
    });
  }
  function watchSwitches() {
    upgradeSwitches(doc.body);
    doc.addEventListener('change', function (e) {
      var t = e.target;
      if (t && t.classList && t.classList.contains('ma-switch-pill')) t.setAttribute('aria-checked', t.checked ? 'true' : 'false');
    }, true);
    if (!window.MutationObserver) return;
    new MutationObserver(function (records) {
      records.forEach(function (r) { r.addedNodes.forEach(function (n) { if (n.nodeType === 1) upgradeSwitches(n); }); });
    }).observe(doc.body, { childList: true, subtree: true });
  }

  function boot() {
    doc.documentElement.classList.add('wp-admin-shell');
    watchSwitches();
    if (!doc.body.classList.contains("adm-no-wpbar")) buildAdminBar();
    tuneSidebar();
  }
  if (doc.readyState === 'loading') doc.addEventListener('DOMContentLoaded', boot); else boot();
})();
