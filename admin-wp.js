/* WordPress-style admin shell: top admin bar + menu details. Visual/navigation only —
   no data writes. Works with the menu generated by scripts/sync-admin-navigation.py. */
(function () {
  'use strict';
  var doc = document;
  function byId(id) { return doc.getElementById(id); }
  function esc(s) { return String(s == null ? '' : s).replace(/[&<>"]/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]; }); }

  function sessionName() {
    try {
      var s = window.MaAdmin && window.MaAdmin.getSession && window.MaAdmin.getSession();
      return (s && (s.name || s.email)) || '';
    } catch (e) { return ''; }
  }

  function buildAdminBar() {
    if (byId('wpAdminBar')) return;
    var bar = doc.createElement('div');
    bar.id = 'wpAdminBar';
    bar.className = 'wp-adminbar';
    bar.setAttribute('role', 'navigation');
    bar.setAttribute('aria-label', 'Toolbar');
    var name = sessionName();
    bar.innerHTML =
      '<ul class="wp-adminbar-left">' +
        '<li class="wp-ab-menu"><button type="button" id="wpAbMenu" aria-label="Menu"><svg viewBox="0 0 24 24" width="20" height="20" aria-hidden="true"><path fill="currentColor" d="M3 6h18v2H3zm0 5h18v2H3zm0 5h18v2H3z"/></svg></button></li>' +
        '<li class="wp-ab-site"><a href="index.html" target="_blank" rel="noopener" title="Visit store"><svg viewBox="0 0 24 24" width="18" height="18" aria-hidden="true"><path fill="currentColor" d="M12 3 2 11h3v9h6v-6h2v6h6v-9h3z"/></svg><span>Muslim Abaya</span></a></li>' +
        '<li class="wp-ab-new"><a href="admin-order-new.html" aria-haspopup="true"><svg viewBox="0 0 24 24" width="16" height="16" aria-hidden="true"><path fill="currentColor" d="M11 4h2v7h7v2h-7v7h-2v-7H4v-2h7z"/></svg><span>New</span></a>' +
          '<ul class="wp-ab-sub"><li><a href="admin-order-new.html">Order</a></li><li><a href="product-manager.html?action=new">Product</a></li></ul></li>' +
        '<li class="wp-ab-link"><a href="admin-orders.html">Orders</a></li>' +
      '</ul>' +
      '<ul class="wp-adminbar-right">' +
        '<li class="wp-ab-user"><span>Howdy' + (name ? ', ' + esc(name) : '') + '</span><span class="wp-ab-avatar" aria-hidden="true"></span>' +
          '<ul class="wp-ab-sub wp-ab-sub-right"><li><button type="button" id="wpAbLogout">Log Out</button></li></ul></li>' +
      '</ul>';
    doc.body.insertBefore(bar, doc.body.firstChild);
    byId('wpAbMenu').addEventListener('click', function () {
      var btn = byId('admMenuBtn') || byId('pnMenuBtn') || byId('menuBtn');
      if (btn) btn.click();
    });
    byId('wpAbLogout').addEventListener('click', function () {
      var out = byId('admLogout');
      if (out) { out.click(); return; }
      try { if (window.MaAdmin && window.MaAdmin.logout) window.MaAdmin.logout(); } catch (e) {}
      location.href = 'admin-login.html';
    });
  }

  function tuneSidebar() {
    var sidebar = byId('pnSide') || byId('admSidebar') || doc.querySelector('.adm-sidebar');
    if (!sidebar) return;
    // Products › Add new product is the same file with ?action=new.
    var here = (location.pathname.split('/').pop() || '') + location.search;
    if (/product-manager\.html\?action=new/.test(here)) {
      sidebar.querySelectorAll('.adm-nav-child').forEach(function (a) {
        var on = /action=new/.test(a.getAttribute('href') || '');
        a.classList.toggle('is-current', on);
        if (on) a.setAttribute('aria-current', 'page'); else a.removeAttribute('aria-current');
      });
    }
    // WordPress keeps "Collapse menu" at the bottom of the sidebar.
    var collapse = byId('admCollapse'), foot = sidebar.querySelector('.adm-sidebar-foot');
    if (collapse && foot && collapse.parentNode !== foot) {
      collapse.classList.add('wp-collapse');
      if (!collapse.querySelector('.wp-collapse-label')) collapse.insertAdjacentHTML('beforeend', '<span class="wp-collapse-label">Collapse menu</span>');
      foot.appendChild(collapse);
    }
    // Keyboard: the flyout opens on focus (CSS :focus-within); Escape closes it.
    sidebar.addEventListener('keydown', function (e) {
      if (e.key !== 'Escape') return;
      var group = e.target.closest && e.target.closest('.adm-nav-group');
      var top = group && group.querySelector('.adm-nav-top');
      if (top && doc.activeElement !== top) top.focus();
    });
  }

  function boot() {
    doc.documentElement.classList.add('wp-admin-shell');
    buildAdminBar();
    tuneSidebar();
  }
  if (doc.readyState === 'loading') doc.addEventListener('DOMContentLoaded', boot); else boot();
})();
