// Generates apps-script/SizeCore.gs from size-core.js so the order check in Apps Script uses exactly the same
// size rules as the website. Run: node scripts/build-size-core.mjs   (--check exits 1 when the .gs copy is stale)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'apps-script/SizeCore.gs');
const next = '// AUTO-GENERATED by scripts/build-size-core.mjs from size-core.js — do not edit by hand.\n' +
  fs.readFileSync(path.join(root, 'size-core.js'), 'utf8');

if (process.argv.includes('--check')) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (current !== next) { console.error('apps-script/SizeCore.gs is stale — run node scripts/build-size-core.mjs'); process.exit(1); }
  console.log('PASS: apps-script/SizeCore.gs matches size-core.js.');
} else {
  fs.writeFileSync(out, next);
  console.log('Wrote apps-script/SizeCore.gs');
}
