// Builds related-home-cards.css: the homepage product-card styles, copied
// rule-for-rule from the homepage stylesheets (in the order index.html loads
// them) and scoped under .pqv-home-related, so the "Related Products" block on
// product pages looks exactly like the homepage cards without touching anything
// else on the page.
//
// Re-run after changing any homepage card CSS:  node scripts/build-related-home-cards.mjs
import fs from 'node:fs';

const SCOPE = '.pqv-home-related';
// Same order as index.html (later files win on equal specificity).
const SOURCES = ['index-home-muslim-abaya.min.css', 'home-glass.css', 'liquid-glass-ui.min.css'];
// Injected at runtime by index-home-muslim-abaya.js (id="ma-home-btn-row"), so it comes last.
const INJECTED =
  '.ah-card .ah-actions{display:flex!important;flex-direction:row!important;flex-wrap:nowrap!important;align-items:stretch;gap:8px;width:100%}' +
  '.ah-card .ah-btn{flex:1 1 0!important;width:0!important;min-width:0!important;border:none!important}' +
  '.ah-card .ah-btn-msg{background:#4a4a4a!important;color:#fff!important}';

const WANT = /\.ah-(card|actions|btn)|\.home-row|\.home-section-(head|title|viewall|body)/;

function stripComments(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, '');
}

// Minimal CSS block parser: returns [{type:'rule', sel, body} | {type:'at', prelude, children|body}]
function parse(css) {
  const out = [];
  let i = 0;
  const n = css.length;
  while (i < n) {
    while (i < n && /[\s;]/.test(css[i])) i++;
    if (i >= n) break;
    let j = i;
    while (j < n && css[j] !== '{' && css[j] !== ';') j++;
    if (j >= n) break;
    const prelude = css.slice(i, j).trim();
    if (css[j] === ';') { i = j + 1; continue; } // @import etc.
    let depth = 1;
    let k = j + 1;
    while (k < n && depth) {
      if (css[k] === '{') depth++;
      else if (css[k] === '}') depth--;
      k++;
    }
    const inner = css.slice(j + 1, k - 1);
    if (/^@(media|supports)/i.test(prelude)) out.push({ type: 'at', prelude, children: parse(inner) });
    else if (/^@/.test(prelude)) out.push({ type: 'raw', prelude, body: inner });
    else out.push({ type: 'rule', sel: prelude, body: inner.trim() });
    i = k;
  }
  return out;
}

const keyframesNeeded = new Set();
const keyframesFound = new Map();

function scopeSelector(sel) {
  return sel
    .split(',')
    .map((s) => s.trim())
    .filter((s) => s && WANT.test(s))
    .map((s) => `${SCOPE} ${s}`)
    .join(',');
}

function emit(nodes) {
  let css = '';
  for (const node of nodes) {
    if (node.type === 'rule') {
      if (/^:root$/.test(node.sel)) {
        const vars = node.body.split(';').map((d) => d.trim()).filter((d) => /^--(ah|home)-/.test(d));
        if (vars.length) css += `${SCOPE}{${vars.join(';')}}\n`;
        continue;
      }
      const sel = scopeSelector(node.sel);
      if (!sel) continue;
      (node.body.match(/animation(?:-name)?\s*:\s*([\w-]+)/g) || []).forEach((m) => {
        keyframesNeeded.add(m.split(':')[1].trim().split(/\s+/)[0]);
      });
      css += `${sel}{${node.body}}\n`;
    } else if (node.type === 'at') {
      const inner = emit(node.children);
      if (inner) css += `${node.prelude}{\n${inner}}\n`;
    } else if (node.type === 'raw' && /^@keyframes\s+/i.test(node.prelude)) {
      keyframesFound.set(node.prelude.replace(/^@keyframes\s+/i, '').trim(), node.body);
    }
  }
  return css;
}

let out =
  '/* GENERATED by scripts/build-related-home-cards.mjs from the homepage card CSS.\n' +
  '   Do not edit by hand; edit the homepage CSS and re-run the script. */\n';
for (const file of SOURCES) {
  out += `/* --- from ${file} --- */\n` + emit(parse(stripComments(fs.readFileSync(file, 'utf8'))));
}
out += '/* --- from index-home-muslim-abaya.js (injected style) --- */\n' + emit(parse(INJECTED));
// Product-page placement only: let the block use the full width under the
// description + reviews columns, like a homepage section.
out += '/* --- product page placement --- */\n' +
  `.pqv-bottom-row>${SCOPE}{grid-column:1 / -1;min-width:0;width:100%}\n`;
for (const name of keyframesNeeded) {
  if (keyframesFound.has(name)) out += `@keyframes ${name}{${keyframesFound.get(name)}}\n`;
}
fs.writeFileSync('related-home-cards.css', out);
console.log(`related-home-cards.css: ${Buffer.byteLength(out)} bytes`);
