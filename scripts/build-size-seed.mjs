// Writes migrations/d1/0002_size_manager_seed.sql from functions/_lib/size-defaults.js: the 8 default templates,
// every category switched off, and published version 1 (also all off, so the website keeps its old size pickers).
// The SQL only adds rows that are not there yet, so running it again never overwrites the owner's edits.
// Usage: node scripts/build-size-seed.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { DEFAULT_TEMPLATES, DEFAULT_CATEGORIES } from '../functions/_lib/size-defaults.js';
import { validateTemplate } from '../functions/_lib/size-store.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'migrations/d1/0002_size_manager_seed.sql');
const SEED_AT = Date.UTC(2026, 9, 30); // fixed, so the file is reproducible
const ACTOR = 'seed';

const q = (v) => (v === null ? 'NULL' : typeof v === 'number' ? String(v) : "'" + String(v).replace(/'/g, "''") + "'");
const row = (...vals) => '(' + vals.map(q).join(', ') + ')';

export function buildSeedConfig() {
  const config = { categories: {}, templates: {}, products: {} };
  DEFAULT_TEMPLATES.forEach((t) => { config.templates[t.id] = validateTemplate(t); });
  DEFAULT_CATEGORIES.forEach((c) => { config.categories[c.category_key] = { template: c.template_id, enabled: c.enabled }; });
  return config;
}

export function buildSeedSql() {
  const config = buildSeedConfig();
  const lines = [
    '-- AUTO-GENERATED by scripts/build-size-seed.mjs from functions/_lib/size-defaults.js. Do not edit by hand.',
    '-- Default size templates for the 8 categories; every category starts OFF (old size pickers stay).',
    '-- INSERT OR IGNORE: rows the owner has already edited are never overwritten.',
    ''
  ];
  Object.values(config.templates).forEach((t) => {
    lines.push('INSERT OR IGNORE INTO size_templates (id, name_bn, name_en, updated_at, updated_by) VALUES ' + row(t.id, t.name_bn, t.name_en, SEED_AT, ACTOR) + ';');
    t.fields.forEach((f, i) => {
      lines.push('INSERT OR IGNORE INTO size_fields (template_id, key, label_bn, label_en, sort_order, required, enabled, allow_custom, default_value, legacy_slots) VALUES ' +
        row(t.id, f.key, f.label_bn, f.label_en, i, f.required ? 1 : 0, f.enabled ? 1 : 0, f.allowCustom ? 1 : 0, f.default, JSON.stringify(f.legacy)) + ';');
      f.options.forEach((o, j) => lines.push('INSERT OR IGNORE INTO size_options (template_id, field_key, value, label_bn, label_en, sort_order) VALUES ' +
        row(t.id, f.key, o.value, o.label_bn, o.label_en, j) + ';'));
    });
  });
  Object.keys(config.categories).forEach((k) => {
    const c = config.categories[k];
    lines.push('INSERT OR IGNORE INTO size_category_settings (category_key, template_id, enabled, updated_at, updated_by) VALUES ' +
      row(k, c.template, c.enabled ? 1 : 0, SEED_AT, ACTOR) + ';');
  });
  const snapshot = JSON.stringify(Object.assign({ version: 1 }, config));
  lines.push('', '-- Version 1 is published only when no version exists yet.');
  lines.push('INSERT INTO size_config_versions (version, snapshot_json, published_at, published_by, note, active) SELECT ' +
    [1, snapshot, SEED_AT, ACTOR, 'default templates, all categories off', 1].map(q).join(', ') +
    ' WHERE NOT EXISTS (SELECT 1 FROM size_config_versions);');
  lines.push("INSERT INTO size_audit_log (at, actor, action, target, before_json, after_json) SELECT " +
    [SEED_AT, ACTOR, 'seed', 'v1'].map(q).join(', ') + ", NULL, NULL WHERE NOT EXISTS (SELECT 1 FROM size_audit_log WHERE action = 'seed');");
  return lines.join('\n') + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const sql = buildSeedSql();
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(out, 'utf8'); } catch (e) {}
    if (cur !== sql) { console.error('build-size-seed: ' + path.relative(root, out) + ' is out of date; run node scripts/build-size-seed.mjs'); process.exit(1); }
    console.log('build-size-seed: up to date');
  } else {
    writeFileSync(out, sql);
    console.log('build-size-seed: wrote ' + path.relative(root, out));
  }
}
