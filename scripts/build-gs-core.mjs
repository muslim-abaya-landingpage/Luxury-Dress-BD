// Generates functions/_lib/gs-core.js from the Apps Script sources so the Cloudflare read path runs
// the SAME order/auth code as Apps Script (no second implementation to drift).
// Run: node scripts/build-gs-core.mjs   (--check exits 1 when the committed file is stale)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sources = ['apps-script/Code.gs', 'apps-script/AdminOrders.gs'];
const exportsList = ['verifyAdminSessionUncached_', 'verifyAdminSession_', 'requireOwnerAdmin_', 'param_', 'adminOrderList_', 'adminOrderGet_',
  'listAdminOrders_', 'adminFraudCheck_', 'adminStaffList_', 'adminCustomerLookup_', 'getAdminStockVariants_', 'getAdminAnalyticsV2_', 'inboxList_', 'inboxThread_', 'getAdminStockLedger_', 'getAdminGrowthData_'];
const services = ['SpreadsheetApp', 'PropertiesService', 'CacheService', 'Utilities', 'Session', 'LockService', 'UrlFetchApp',
  'MailApp', 'GmailApp', 'ScriptApp', 'ContentService', 'HtmlService', 'Logger', 'DriveApp', 'CalendarApp', 'XmlService'];

function build() {
  const body = sources.map((file) => `// ── ${file} ──\n` + fs.readFileSync(path.join(root, file), 'utf8')).join('\n');
  return `// AUTO-GENERATED by scripts/build-gs-core.mjs from ${sources.join(', ')} — do not edit by hand.
// createCore(env) evaluates the Apps Script functions against a read-only stand-in for Google services.
/* eslint-disable */
export function createCore(env) {
  ${services.map((s) => `var ${s} = env.${s};`).join(' ')}
  var console = env.console || globalThis.console;
${body}
  return { ${exportsList.map((n) => `${n}: ${n}`).join(', ')} };
}
`;
}

const out = path.join(root, 'functions/_lib/gs-core.js');
const next = build();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (current !== next) { console.error('functions/_lib/gs-core.js is stale — run node scripts/build-gs-core.mjs'); process.exit(1); }
  console.log('PASS: Cloudflare read core matches the Apps Script sources.');
} else {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, next);
  console.log('Wrote functions/_lib/gs-core.js (' + Math.round(next.length / 1024) + ' KB).');
}
